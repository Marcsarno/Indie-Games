# Refresh the art kit from the game: copy the engine files the studio needs and bundle the
# examples into engine/examples.js. Run after changing the renderer, materials or rigs:
#   python3 tools/artkit-sync.py
import json, os, shutil, glob
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src, kit = os.path.join(root, 'game', 'js'), os.path.join(root, 'art-kit')
ENGINE = ['core', 'rig', 'actors', 'monsters', 'items', 'world', 'outdoor', 'review']
for n in ENGINE: shutil.copy(os.path.join(src, n + '.js'), os.path.join(kit, 'engine', n + '.js'))
ex = {}
for f in sorted(glob.glob(os.path.join(kit, 'examples', '*.js'))): ex[os.path.basename(f)[:-3]] = open(f).read()
open(os.path.join(kit, 'engine', 'examples.js'), 'w').write('// generated by tools/artkit-sync.py from art-kit/examples/\nconst ART_EXAMPLES = ' + json.dumps(ex, indent=0) + ';\n')
print('engine:', ', '.join(ENGINE), '| examples:', ', '.join(ex))
